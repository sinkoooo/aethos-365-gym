document.addEventListener('DOMContentLoaded', () => {
    
    // Elements
    const recipesGrid = document.getElementById('recipesGrid');
    const searchInput = document.getElementById('searchInput');
    const filterButtons = document.querySelectorAll('.filter-group .btn-filter');
    const totalTriedBadge = document.getElementById('totalTriedBadge');
    
    // Modal Elements
    const recipeModal = document.getElementById('recipeModal');
    const btnCloseModal = document.getElementById('btnCloseModal');
    const modalStage = document.getElementById('modalStage');
    const modalTitle = document.getElementById('modalTitle');
    const modalTitleEn = document.getElementById('modalTitleEn');
    const modalPrepTime = document.getElementById('modalPrepTime');
    const modalIngredients = document.getElementById('modalIngredients');
    const modalSteps = document.getElementById('modalSteps');
    const modalBenefit = document.getElementById('modalBenefit');
    const modalTipBox = document.getElementById('modalTipBox');
    const modalTipText = document.getElementById('modalTipText');

    // State
    let currentFilter = 'all';
    let searchQuery = '';
    let triedRecipes = [];
    try {
        triedRecipes = JSON.parse(localStorage.getItem('babyTriedRecipes')) || [];
        if (!Array.isArray(triedRecipes)) {
            triedRecipes = [];
        }
    } catch (e) {
        console.warn("LocalStorage is not accessible. Using in-memory fallback.", e);
    }

    // Initialize Page
    updateTriedProgress();
    renderRecipes();

    // Event Listeners for Filters
    filterButtons.forEach(btn => {
        btn.addEventListener('click', () => {
            filterButtons.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            currentFilter = btn.dataset.stage;
            renderRecipes();
        });
    });

    // Event Listener for Search
    searchInput.addEventListener('input', (e) => {
        searchQuery = e.target.value.toLowerCase().trim();
        renderRecipes();
    });

    // Close Modal Event Listeners
    btnCloseModal.addEventListener('click', closeModal);
    recipeModal.addEventListener('click', (e) => {
        if (e.target === recipeModal) {
            closeModal();
        }
    });
    
    // Escape key closes modal
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && recipeModal.classList.contains('active')) {
            closeModal();
        }
    });

    // Render Recipes Function
    function renderRecipes() {
        recipesGrid.innerHTML = '';
        
        const filteredRecipes = recipesData.filter(recipe => {
            // Stage filter matching
            const matchesStage = (currentFilter === 'all') || (recipe.stage === parseInt(currentFilter));
            
            // Search text matching
            const matchesSearch = recipe.title.toLowerCase().includes(searchQuery) ||
                                 recipe.titleEn.toLowerCase().includes(searchQuery) ||
                                 recipe.desc.toLowerCase().includes(searchQuery) ||
                                 recipe.ingredients.some(ing => ing.toLowerCase().includes(searchQuery));
            
            return matchesStage && matchesSearch;
        });

        if (filteredRecipes.length === 0) {
            recipesGrid.innerHTML = `
                <div style="grid-column: 1/-1; text-align: center; padding: 3rem 1rem; color: var(--text-muted);">
                    <span style="font-size: 3rem;">🔍</span>
                    <h3 style="margin-top: 1rem; color: var(--accent-teal);">कोई रेसिपी नहीं मिली</h3>
                    <p>कृपया कोई दूसरा शब्द खोजें या फ़िल्टर बदलें।</p>
                </div>
            `;
            return;
        }

        filteredRecipes.forEach(recipe => {
            const isTried = triedRecipes.includes(recipe.id);
            const card = document.createElement('div');
            card.className = `recipe-card ${isTried ? 'tried' : ''}`;
            card.dataset.id = recipe.id;

            let stageName = '';
            let stageBadgeClass = '';
            if (recipe.stage === 1) {
                stageName = 'स्टेज 1 (6+ महीने)';
                stageBadgeClass = 'badge-stage1';
            } else if (recipe.stage === 2) {
                stageName = 'स्टेज 2 (7+ महीने)';
                stageBadgeClass = 'badge-stage2';
            } else {
                stageName = 'स्टेज 3 (8+ महीने)';
                stageBadgeClass = 'badge-stage3';
            }

            card.innerHTML = `
                <div class="tried-stamp">✓</div>
                <div class="card-header">
                    <span class="stage-badge ${stageBadgeClass}">${stageName}</span>
                </div>
                <div class="card-body">
                    <h3 class="recipe-title">${recipe.title}</h3>
                    <div class="recipe-title-en">${recipe.titleEn}</div>
                    <p class="recipe-desc">${recipe.desc}</p>
                    <div class="recipe-meta">
                        <span class="meta-time">⏱️ ${recipe.time}</span>
                        <button class="btn-tried-toggle">
                            <span>${isTried ? 'चख लिया! ✓' : 'चख लिया?'}</span>
                        </button>
                    </div>
                </div>
            `;

            // Open modal when card clicked (but not when "tried" button is clicked)
            card.addEventListener('click', (e) => {
                if (e.target.closest('.btn-tried-toggle')) {
                    e.stopPropagation();
                    toggleTried(recipe.id, card);
                } else {
                    openModal(recipe);
                }
            });

            recipesGrid.appendChild(card);
        });
    }

    // Toggle Tried State
    function toggleTried(id, cardElement) {
        const index = triedRecipes.indexOf(id);
        if (index > -1) {
            // Remove from list
            triedRecipes.splice(index, 1);
            cardElement.classList.remove('tried');
            cardElement.querySelector('.btn-tried-toggle span').textContent = 'चख लिया?';
        } else {
            // Add to list
            triedRecipes.push(id);
            cardElement.classList.add('tried');
            cardElement.querySelector('.btn-tried-toggle span').textContent = 'चख लिया! ✓';
        }
        
        try {
            localStorage.setItem('babyTriedRecipes', JSON.stringify(triedRecipes));
        } catch (e) {
            console.warn("Could not save to LocalStorage:", e);
        }
        updateTriedProgress();
    }

    // Update Progress Bar/Badge
    function updateTriedProgress() {
        const total = recipesData.length;
        const triedCount = triedRecipes.length;
        totalTriedBadge.textContent = `${triedCount}/${total}`;
    }

    // Open Modal Details
    function openModal(recipe) {
        let stageName = '';
        let stageBadgeClass = '';
        if (recipe.stage === 1) {
            stageName = 'स्टेज 1: सिंगल सामग्री (6+ महीने)';
            stageBadgeClass = 'badge-stage1';
        } else if (recipe.stage === 2) {
            stageName = 'स्टेज 2: न्यूट्रिएंट्स कॉम्बो (7+ महीने)';
            stageBadgeClass = 'badge-stage2';
        } else {
            stageName = 'स्टेज 3: संतुलित शुरुआत भोजन (8+ महीने)';
            stageBadgeClass = 'badge-stage3';
        }

        modalStage.className = `modal-stage ${stageBadgeClass}`;
        modalStage.textContent = stageName;
        modalTitle.textContent = recipe.title;
        modalTitleEn.textContent = recipe.titleEn;
        modalPrepTime.textContent = recipe.time;
        
        // Ingredients
        modalIngredients.innerHTML = '';
        recipe.ingredients.forEach(ing => {
            const li = document.createElement('li');
            li.textContent = ing;
            modalIngredients.appendChild(li);
        });

        // Steps
        modalSteps.innerHTML = '';
        recipe.steps.forEach((step, idx) => {
            const li = document.createElement('li');
            li.setAttribute('data-step', idx + 1);
            li.textContent = step;
            modalSteps.appendChild(li);
        });

        // Nutrition benefit
        modalBenefit.textContent = recipe.benefit;

        // Custom Tip
        if (recipe.tip) {
            modalTipBox.style.display = 'flex';
            modalTipText.textContent = recipe.tip;
        } else {
            modalTipBox.style.display = 'none';
        }

        // Show Modal
        recipeModal.classList.add('active');
        document.body.style.overflow = 'hidden'; // prevent scrolling underneath
    }

    // Close Modal
    function closeModal() {
        recipeModal.classList.remove('active');
        document.body.style.overflow = '';
    }

});
